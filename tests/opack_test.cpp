#include "headunit/opack.hpp"

#include <array>
#include <cmath>
#include <iostream>
#include <limits>
#include <random>
#include <optional>
#include <stdexcept>
#include <string>

namespace {
using V = headunit::OpackValue;
using B = V::Bytes;
void check(bool condition) {
  if (!condition) throw std::runtime_error("OPACK test failed");
}
B hex(const std::string& text) {
  B bytes;
  for (std::size_t i = 0; i < text.size(); i += 2)
    bytes.push_back(static_cast<std::uint8_t>(std::stoul(text.substr(i, 2), nullptr, 16)));
  return bytes;
}
template <class F>
void rejects(F&& action) {
  bool caught = false;
  try {
    action();
  } catch (const std::invalid_argument&) {
    caught = true;
  }
  check(caught);
}
void roundtrip(const V& value) {
  check(headunit::decode_opack(headunit::encode_opack(value)) == value);
}
}  // namespace

int main() try {
  // Bytes generated by the installed Apple CoreUtils codec from synthetic
  // property lists, independent of our implementation.
  const auto integers = headunit::decode_opack(
      hex("d83080317fff31008032ff7fffff307f31800032ffffff7f330000008000000000"));
  check(integers ==
        V{V::Array{V{std::int64_t{-128}}, V{std::int64_t{-129}}, V{std::int64_t{-32768}},
                   V{std::int64_t{-32769}}, V{std::int64_t{127}}, V{std::int64_t{128}},
                   V{std::int64_t{2147483647}}, V{std::int64_t{2147483648}}}});
  check(headunit::decode_opack(hex("d47178717836000000000000f03fa0")) ==
        V{V::Array{V{B{'x'}}, V{B{'x'}}, V{1.0}, V{1.0}}});
  check(headunit::decode_opack(hex("d343666f6f43666f6fa1")) ==
        V{V::Array{V{std::string("foo")}, V{std::string("foo")}, V{std::string("foo")}}});
  check(headunit::decode_opack(hex("d37261624178a0")) ==
        V{V::Array{V{B{'a', 'b'}}, V{std::string("x")}, V{B{'a', 'b'}}}});
  check(headunit::decode_opack(
            hex("e244646174617862706c69737430304b646973706c6179555549446124"
                "30303030303030302d303030302d343030302d383030302d303030303030303030303031")) ==
        V{V::Dictionary{{"data", V{B{'b', 'p', 'l', 'i', 's', 't', '0', '0'}}},
                        {"displayUUID", V{std::string("00000000-0000-4000-8000-000000000001")}}}});
  for (auto n : std::array<std::int64_t, 13>{-1, -2, 0, 39, 40, 127, 128, 255, 256, 65535, 65536,
                                             std::numeric_limits<std::int64_t>::min(),
                                             std::numeric_limits<std::int64_t>::max()})
    roundtrip(V{n});
  roundtrip(V{});
  roundtrip(V{true});
  roundtrip(V{false});
  roundtrip(V{-123.5});
  roundtrip(V{std::string("température\0zone", 17)});
  for (auto n : {0u, 1u, 2u, 32u, 33u, 255u, 256u, 65535u, 65536u}) {
    roundtrip(V{B(n, 0x81)});
    roundtrip(V{std::string(n, 'x')});
  }
  V::Array list(33, V{std::int64_t{4}});
  roundtrip(V{list});
  V::Dictionary dictionary;
  for (unsigned i = 0; i < 16; ++i)
    dictionary.emplace(std::to_string(i), V{list});
  roundtrip(V{dictionary});
  check(headunit::decode_opack(hex("df416103")) == V{V::Array{V{std::string("a")}}});
  check(headunit::decode_opack(hex("ef41610a03")) == V{V::Dictionary{{"a", V{std::int64_t{2}}}}});
  check(headunit::decode_opack(hex("6f686900")) == V{std::string("hi")});
  check(headunit::decode_opack(hex("350000c03f")) == V{1.5});
  // Wider length/index forms independently accepted by CoreUtils.
  check(headunit::decode_opack(hex("64010000000000000061")) == V{std::string("a")});
  check(headunit::decode_opack(hex("9402000000000000006162")) == V{B{'a', 'b'}});
  for (const auto* extended : {"d24161c300000000", "d24161c40000000000000000"})
    check(headunit::decode_opack(hex(extended)) ==
          V{V::Array{V{std::string("a")}, V{std::string("a")}}});
  const auto wide = headunit::encode_opack(V{std::string(65536, 'a')});
  check(wide[0] == 0x63 && wide[1] == 0 && wide[2] == 0 && wide[3] == 1 && wide[4] == 0);
  const auto sample = headunit::encode_opack(V{dictionary});
  for (std::size_t size = 0; size < sample.size(); ++size)
    rejects([&] { (void)headunit::decode_opack(std::span(sample).first(size)); });
  for (const auto* malformed : {"",
                                "00",
                                "03",
                                "05",
                                "34",
                                "df",
                                "df4161",
                                "ef416103",
                                "e20809",
                                "e241610941610a",
                                "a0",
                                "d240a0",
                                "d230ffa0",
                                "c4ffffffff",
                                "64ffffffff",
                                "94ffffffff",
                                "0404",
                                "42c080",
                                "43eda080",
                                "44f4908080",
                                "36000000000000f07f"})
    rejects([&] { (void)headunit::decode_opack(hex(malformed)); });
  auto small = headunit::OpackLimits{};
  small.nodes = 4;
  rejects([&] { (void)headunit::decode_opack(hex("d50101010101"), small); });
  rejects([&] { (void)headunit::encode_opack(V{list}, small); });
  small = {};
  small.depth = 2;
  rejects([&] { (void)headunit::decode_opack(hex("d1d1d104"), small); });
  small = {};
  small.expanded_bytes = 5;
  rejects([&] { (void)headunit::decode_opack(hex("d3726162a0a0"), small); });
  // Deterministic malformed-input smoke check, also run under sanitizers.
  std::mt19937 random(260926);
  for (unsigned iteration = 0; iteration < 20000; ++iteration) {
    B input(random() % 96);
    for (auto& byte : input)
      byte = static_cast<std::uint8_t>(random());
    std::optional<V> value;
    try {
      value = headunit::decode_opack(input);
    } catch (const std::invalid_argument&) {
    }
    if (value) roundtrip(*value);
  }
  return 0;
} catch (const std::exception& error) {
  std::cerr << error.what() << '\n';
  return 1;
}
